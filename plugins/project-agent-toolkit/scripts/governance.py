def coverage_report(config: dict[str, Any]) -> dict[str, Any]:
    authorities = {
        str(item.get("id"))
        for item in config.get("authorities", [])
        if isinstance(item, dict) and item.get("id")
    }
    routes = [
        item
        for item in config.get("routes", [])
        if isinstance(item, dict) and isinstance(item.get("id"), str)
    ]
    routed_authorities = {
        str(authority)
        for route in routes
        for authority in route.get("read", [])
    }
    tests = [
        item
        for item in config.get("route_tests", [])
        if isinstance(item, dict)
    ]
    tested_routes = {
        route
        for test in tests
        for route in test.get("expect_routes", [])
    }
    capabilities = {
        str(item.get("id"))
        for item in config.get("capabilities", [])
        if isinstance(item, dict) and item.get("id")
    }
    capability_tests = [
        item
        for item in config.get("capability_tests", [])
        if isinstance(item, dict)
    ]
    tested_capabilities = {
        capability
        for test in capability_tests
        for capability in test.get("expect_capabilities", [])
    }
    profiles = set(config.get("validation", {}).get("profiles", {}).keys())
    referenced_profiles = {
        str(profile)
        for route in routes
        for profile in route.get("validation", [])
    }
    referenced_profiles.update(
        str(profile)
        for profile in config.get("validation", {}).get("default_profiles", [])
    )
    referenced_profiles.update(
        str(rule.get("guard"))
        for rule in config.get("rules", [])
        if isinstance(rule, dict) and rule.get("guard")
    )
    for interface in config.get("development_interfaces", []):
        if not isinstance(interface, dict):
            continue
        interface_guards = interface.get("guard_profiles", [])
        if isinstance(interface_guards, dict):
            referenced_profiles.update(
                str(profile)
                for selected in interface_guards.values()
                if isinstance(selected, list)
                for profile in selected
            )
        elif isinstance(interface_guards, list):
            referenced_profiles.update(str(profile) for profile in interface_guards)
    unguarded_rules = [
        str(rule.get("id", "<unnamed>"))
        for rule in config.get("rules", [])
        if isinstance(rule, dict) and not rule.get("guard")
    ]
    gaps = {
        "unrouted_authorities": sorted(authorities - routed_authorities),
        "untested_routes": sorted(
            str(route["id"])
            for route in routes
            if route["id"] != "default" and route["id"] not in tested_routes
        ),
        "untested_capabilities": sorted(
            capabilities - tested_capabilities
        ),
        "unused_validation_profiles": sorted(profiles - referenced_profiles),
        "unguarded_rules": sorted(unguarded_rules),
        "failing_route_tests": [
            asdict(finding)
            for finding in route_test_findings(config)
            if finding.severity == "error"
        ],
        "failing_capability_tests": [
            asdict(finding)
            for finding in capability_test_findings(config)
            if finding.severity == "error"
        ],
    }
    gaps["complete"] = not any(value for key, value in gaps.items() if key != "complete")
    return gaps


def add_visual_governance_defaults(config: dict[str, Any]) -> None:
    routes = config.setdefault("routes", [])
    if not isinstance(routes, list):
        return
    route_ids = {
        str(route.get("id"))
        for route in routes
        if isinstance(route, dict) and route.get("id")
    }
    validation = config.setdefault("validation", {})
    if not isinstance(validation, dict):
        return
    profiles = validation.setdefault("profiles", {})
    if not isinstance(profiles, dict):
        return
    default_profiles = [
        str(profile)
        for profile in validation.get("default_profiles", [])
        if isinstance(profile, str)
    ]
    profiles.setdefault(
        "visual",
        {
            "extends": default_profiles,
            "commands": [],
        },
    )

    if "visual" not in route_ids:
        authority_ids = {
            str(authority.get("id"))
            for authority in config.get("authorities", [])
            if isinstance(authority, dict) and authority.get("id")
        }
        read = [
            authority
            for authority in ("architecture", "rules", "workflow", "state")
            if authority in authority_ids
        ]
        visual_route = {
            "id": "visual",
            "terms": [
                "ui",
                "visual",
                "render",
                "drawing",
                "modeling",
                "3d model",
                "character model",
                "mesh",
                "animation",
                "vfx",
                "layout",
                "scene",
                "map",
                "terrain",
                "css",
                "style",
                "font",
                "icon",
                "responsive",
                "material",
                "texture",
                "shader",
                "lighting",
                "camera",
                "art",
            ],
            "paths": [],
            "read": read,
            "validation": ["visual"],
        }
        default_index = next(
            (
                index
                for index, route in enumerate(routes)
                if isinstance(route, dict) and route.get("id") == "default"
            ),
            len(routes),
        )
        routes.insert(default_index, visual_route)

    policy = config.setdefault("visual_validation", {})
    if isinstance(policy, dict):
        selected_routes = policy.setdefault("routes", ["visual"])
        if isinstance(selected_routes, list) and "visual" not in selected_routes:
            selected_routes.append("visual")
        policy.setdefault("artifact_min_count", 1)
        policy.setdefault("min_review_checks", 1)
        policy.setdefault("artifact_max_age_seconds", 3600)
        policy["require_review"] = True
        policy["require_surface"] = True

    route_tests = config.setdefault("route_tests", [])
    if isinstance(route_tests, list) and not any(
        isinstance(test, dict) and test.get("id") == "visual-route"
        for test in route_tests
    ):
        actual = route_details(config, "inspect UI layout", [])
        route_tests.append(
            {
                "id": "visual-route",
                "task": "inspect UI layout",
                "paths": [],
                "expect_routes": actual["routes"],
                "expect_documents": actual["documents"],
                "expect_validation_profiles": actual["validation_profiles"],
            }
        )


def migrate_config(config: dict[str, Any]) -> dict[str, Any]:
    version = config.get("version")
    if version == CURRENT_VERSION:
        return config
    if version not in {1, 2, 3}:
        raise ValueError(f"cannot migrate configuration version {version!r}")
    migrated = json.loads(json.dumps(config))
    if version == 1:
        migrated["version"] = 2
        migrated.setdefault("project", {"name": "Project"})
        migrated.setdefault(
            "adapters",
            {
                "outputs": [
                    {"kind": "agents", "path": "AGENTS.md"},
                    {"kind": "copilot", "path": ".github/copilot-instructions.md"},
                ]
            },
        )
        old_commands = migrated.get("validation", {}).pop("commands", [])
        validation = migrated.setdefault("validation", {})
        validation.setdefault(
            "profiles",
            {
                "fast": {
                    "commands": [
                        {
                            "run": command,
                            "proves": "Project-configured fast validation",
                        }
                        for command in old_commands
                    ]
                }
            },
        )
        validation.setdefault("default_profiles", ["fast"])
        route_tests = []
        for route in migrated.get("routes", []):
            if not isinstance(route, dict) or not route.get("id"):
                continue
            route.setdefault("validation", ["fast"])
            terms = route.get("terms", [])
            paths = route.get("paths", [])
            test_task = str(terms[0]) if terms else ""
            test_paths = [str(paths[0])] if paths and route["id"] != "default" else []
            route_tests.append(
                {
                    "id": f"{route['id']}-route",
                    "task": test_task,
                    "paths": test_paths,
                }
            )
        for route_test in route_tests:
            actual = route_details(
                migrated,
                str(route_test["task"]),
                [str(path) for path in route_test["paths"]],
            )
            route_test["expect_routes"] = actual["routes"]
            route_test["expect_documents"] = actual["documents"]
            route_test["expect_validation_profiles"] = actual["validation_profiles"]
        migrated.setdefault("route_tests", route_tests)
        migrated.setdefault("rules", [])
        migrated.setdefault("evidence", {"directory": ".agent-evidence"})

    migrated.setdefault("development_interfaces", [])
    for interface in migrated.get("development_interfaces", []):
        if (
            isinstance(interface, dict)
            and str(interface.get("protocol", "")).lower() == "mcp"
            and isinstance(interface.get("guard_profiles"), list)
        ):
            legacy_profiles = [
                str(profile)
                for profile in interface["guard_profiles"]
                if isinstance(profile, str) and profile
            ]
            required = list(MCP_GUARD_KINDS)
            if interface.get("production_allowed") is False:
                required.append("release")
            interface["guard_profiles"] = {
                guard_kind: list(legacy_profiles)
                for guard_kind in required
            }
    add_visual_governance_defaults(migrated)
    migrated["version"] = CURRENT_VERSION
    return migrated


def print_audit(findings: list[Finding], metrics: dict[str, Any], as_json: bool) -> None:
    if as_json:
        print(
            json.dumps(
                {
                    "metrics": metrics,
                    "findings": [asdict(finding) for finding in findings],
                },
                indent=2,
            )
        )
        return
    errors = sum(f.severity == "error" for f in findings)
    warnings = sum(f.severity == "warning" for f in findings)
    print(
        f"Agent governance audit: {errors} error(s), {warnings} warning(s); "
        f"always-loaded {metrics.get('always_loaded_chars', 0)} chars"
    )
    for finding in findings:
        location = f" [{finding.path}]" if finding.path else ""
        print(f"{finding.severity.upper():7} {finding.code}{location}: {finding.message}")


