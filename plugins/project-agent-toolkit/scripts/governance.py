@dataclass(frozen=True)
class Finding:
    severity: str
    code: str
    message: str
    path: str | None = None


def normalize_project_relative(relative: str) -> str:
    """Normalize a project-relative path without depending on host path aliases."""
    portable = relative.replace("\\", "/")
    if (
        not portable
        or PurePosixPath(portable).is_absolute()
        or re.match(r"^[A-Za-z]:/", portable)
    ):
        raise ValueError(f"path must be project-relative: {relative}")
    parts: list[str] = []
    for part in portable.split("/"):
        if part in {"", "."}:
            continue
        if part == "..":
            if not parts:
                raise ValueError(f"path escapes project root: {relative}")
            parts.pop()
            continue
        parts.append(part)
    return "/".join(parts) if parts else "."


def project_path(root: Path, relative: str) -> Path:
    normalized = normalize_project_relative(relative)
    candidate = (root / Path(*PurePosixPath(normalized).parts)).resolve()
    try:
        candidate.relative_to(root.resolve())
    except ValueError as exc:
        raise ValueError(f"path escapes project root: {relative}") from exc
    return candidate


def posix(relative: str | Path) -> str:
    return str(relative).replace("\\", "/")


def read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return payload


def line_count(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def configured_positive_int(
    value: Any,
    fallback: int,
    findings: list[Finding],
    code: str,
    message: str,
) -> int:
    if isinstance(value, bool):
        findings.append(Finding("error", code, message, CONFIG_NAME))
        return fallback
    try:
        parsed = int(value)
    except (TypeError, ValueError):
        findings.append(Finding("error", code, message, CONFIG_NAME))
        return fallback
    if parsed < 1:
        findings.append(Finding("error", code, message, CONFIG_NAME))
        return fallback
    return parsed


def ensure_evidence_ignore(root: Path) -> bool:
    """Add the default transient receipt directory to Git ignore additively."""
    path = root / ".gitignore"
    entry = ".agent-evidence/"
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    normalized = {
        line.strip().replace("\\", "/")
        for line in current.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    }
    if entry in normalized or entry.rstrip("/") in normalized:
        return False
    prefix = "" if not current or current.endswith("\n") else "\n"
    block = f"{prefix}# Project Agent Toolkit transient evidence\n{entry}\n"
    path.write_text(current + block, encoding="utf-8")
    return True


def git_ignores_path(root: Path, relative: str) -> bool:
    """Return whether Git excludes a path that may not exist yet."""
    try:
        normalized = normalize_project_relative(relative)
        project_path(root, normalized)
    except ValueError:
        return False
    result = subprocess.run(
        ["git", "check-ignore", "--quiet", normalized],
        cwd=root,
        capture_output=True,
        check=False,
    )
    return result.returncode == 0


def iter_template_files(profile: str) -> Iterable[tuple[Path, Path]]:
    for source_root in (TEMPLATE_ROOT / "minimal", TEMPLATE_ROOT / profile):
        if not source_root.exists():
            continue
        for source in sorted(p for p in source_root.rglob("*") if p.is_file()):
            yield source, source.relative_to(source_root)


def initialize(root: Path, profile: str, force: bool) -> int:
    root.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    preserved: list[str] = []
    seen: set[str] = set()
    for source, relative in iter_template_files(profile):
        key = posix(relative)
        if key in seen:
            continue
        seen.add(key)
        target = root / relative
        if target.exists() and not force:
            preserved.append(key)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        written.append(key)

    ignore_updated = ensure_evidence_ignore(root)

    print(f"Initialized governance in {root}")
    if written:
        print("Created:")
        for path in written:
            print(f"  {path}")
    if preserved:
        print("Preserved existing files:")
        for path in preserved:
            print(f"  {path}")
    if ignore_updated:
        print("Updated additively:")
        print("  .gitignore")
    print(
        "Next: configure at least one real validation command in "
        ".agent-governance.json, then run `governance.py check`."
    )
    return 0


def load_config(root: Path) -> tuple[dict[str, Any] | None, list[Finding]]:
    path = root / CONFIG_NAME
    if not path.exists():
        return None, [
            Finding(
                "error",
                "config.missing",
                f"{CONFIG_NAME} is missing; run the bootstrap command first",
                CONFIG_NAME,
            )
        ]
    try:
        config = read_json(path)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        return None, [Finding("error", "config.invalid", str(exc), CONFIG_NAME)]
    return config, []


def markdown_link_findings(root: Path, relative: str) -> list[Finding]:
    path = project_path(root, relative)
    findings: list[Finding] = []
    if not path.exists() or path.suffix.lower() != ".md":
        return findings
    text = path.read_text(encoding="utf-8")
    for raw_target in MARKDOWN_LINK.findall(text):
        target = raw_target.strip().strip("<>")
        target = target.split(maxsplit=1)[0].strip("\"'")
        if not target or target.startswith(("#", "mailto:")):
            continue
        if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target):
            continue
        target = unquote(target.split("#", 1)[0])
        if not target:
            continue
        resolved = (path.parent / target).resolve()
        try:
            resolved.relative_to(root.resolve())
        except ValueError:
            findings.append(
                Finding(
                    "error",
                    "link.escapes-root",
                    f"link target escapes project root: {raw_target}",
                    relative,
                )
            )
            continue
        if not resolved.exists():
            findings.append(
                Finding(
                    "error",
                    "link.missing",
                    f"link target does not exist: {raw_target}",
                    relative,
                )
            )
    return findings


def normalized_paragraphs(path: Path, minimum: int) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    result: dict[str, str] = {}
    for paragraph in re.split(r"\n\s*\n", text):
        cleaned = " ".join(
            line.strip()
            for line in paragraph.splitlines()
            if line.strip() and not line.lstrip().startswith(("#", "```"))
        )
        normalized = re.sub(r"\s+", " ", cleaned).strip().lower()
        if len(normalized) >= minimum:
            result[normalized] = cleaned
    return result


def matches_allowed(path: str, patterns: list[str]) -> bool:
    normalized = posix(path)
    pure = PurePosixPath(normalized)
    return any(
        fnmatch.fnmatchcase(normalized, pattern) or pure.match(pattern)
        for pattern in patterns
    )


def task_term_matches(task: str, term: str) -> bool:
    normalized = term.strip().lower()
    if not normalized:
        return False
    pattern = re.escape(normalized).replace(r"\ ", r"\s+")
    return re.search(rf"(?<!\w){pattern}(?!\w)", task.lower()) is not None


def audit_codex_configuration(
    root: Path,
) -> tuple[list[Finding], dict[str, Any]]:
    findings: list[Finding] = []
    metrics: dict[str, Any] = {
        "codex_config_present": False,
        "agent_role_count": 0,
        "agent_roles": [],
        "agent_model_override_count": 0,
        "agent_reasoning_override_count": 0,
    }
    config_path = root / ".codex" / "config.toml"
    if config_path.is_file():
        metrics["codex_config_present"] = True
        try:
            config = tomllib.loads(config_path.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError) as exc:
            findings.append(
                Finding(
                    "error",
                    "codex.config-invalid",
                    f"Codex configuration is not valid TOML: {exc}",
                    ".codex/config.toml",
                )
            )
        else:
            agents = config.get("agents", {})
            if isinstance(agents, dict):
                for stale_key in ("max_depth", "job_max_runtime_seconds"):
                    if stale_key in agents:
                        findings.append(
                            Finding(
                                "warning",
                                "codex.agent-setting-stale",
                                (
                                    f"agents.{stale_key} is not part of the "
                                    "current documented Codex agent configuration"
                                ),
                                ".codex/config.toml",
                            )
                        )

    role_directory = root / ".codex" / "agents"
    if not role_directory.is_dir():
        return findings, metrics

    names: dict[str, str] = {}
    role_paths = sorted(role_directory.glob("*.toml"))
    for role_path in role_paths:
        relative = posix(role_path.relative_to(root))
        try:
            role = tomllib.loads(role_path.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError) as exc:
            findings.append(
                Finding(
                    "error",
                    "codex.role-invalid",
                    f"agent role is not valid TOML: {exc}",
                    relative,
                )
            )
            continue

        valid = True
        for field in ("name", "description", "developer_instructions"):
            value = role.get(field)
            if not isinstance(value, str) or not value.strip():
                valid = False
                findings.append(
                    Finding(
                        "error",
                        "codex.role-field",
                        f"agent role requires a non-empty {field}",
                        relative,
                    )
                )
        name = role.get("name")
        if isinstance(name, str) and name.strip():
            normalized_name = name.strip()
            previous = names.get(normalized_name)
            if previous is not None:
                valid = False
                findings.append(
                    Finding(
                        "error",
                        "codex.role-duplicate",
                        (
                            f"agent role name {normalized_name!r} is already "
                            f"defined by {previous}"
                        ),
                        relative,
                    )
                )
            else:
                names[normalized_name] = relative
        if valid:
            metrics["agent_roles"].append(name.strip())
        if isinstance(role.get("model"), str) and role["model"].strip():
            metrics["agent_model_override_count"] += 1
        if (
            isinstance(role.get("model_reasoning_effort"), str)
            and role["model_reasoning_effort"].strip()
        ):
            metrics["agent_reasoning_override_count"] += 1

    metrics["agent_roles"].sort()
    metrics["agent_role_count"] = len(metrics["agent_roles"])
    return findings, metrics


def audit(root: Path) -> tuple[list[Finding], dict[str, Any]]:
    config, findings = load_config(root)
    metrics: dict[str, Any] = {
        "root": str(root),
        "entrypoint_lines": {},
        "always_loaded_chars": 0,
        "authority_count": 0,
        "route_count": 0,
        "capability_count": 0,
        "development_interface_count": 0,
        "visual_route_count": 0,
        "codex_config_present": False,
        "agent_role_count": 0,
        "agent_roles": [],
        "agent_model_override_count": 0,
        "agent_reasoning_override_count": 0,
    }
    if config is None:
        return findings, metrics

    codex_findings, codex_metrics = audit_codex_configuration(root)
    findings.extend(codex_findings)
    metrics.update(codex_metrics)

    if config.get("version") != CURRENT_VERSION:
        findings.append(
            Finding(
                "error",
                "config.version",
                (
                    f"configuration version must be {CURRENT_VERSION}; "
                    "run `governance.py upgrade`"
                ),
                CONFIG_NAME,
            )
        )

    limits = config.get("limits", {})
    if not isinstance(limits, dict):
        findings.append(Finding("error", "config.limits", "limits must be an object", CONFIG_NAME))
        limits = {}
    entrypoint_limit = configured_positive_int(
        limits.get("entrypoint_max_lines", 120),
        120,
        findings,
        "limits.entrypoint-max-lines",
        "limits.entrypoint_max_lines must be a positive integer",
    )
    context_limit = configured_positive_int(
        limits.get("always_loaded_max_chars", 30000),
        30000,
        findings,
        "limits.always-loaded-max-chars",
        "limits.always_loaded_max_chars must be a positive integer",
    )
    duplicate_min = configured_positive_int(
        limits.get("duplicate_paragraph_min_chars", 180),
        180,
        findings,
        "limits.duplicate-paragraph-min-chars",
        "limits.duplicate_paragraph_min_chars must be a positive integer",
    )
    capability_owner_limit = configured_positive_int(
        limits.get("capability_owner_max_count", 8),
        8,
        findings,
        "limits.capability-owner-max-count",
        "limits.capability_owner_max_count must be a positive integer",
    )

    entrypoints = config.get("entrypoints", [])
    if not isinstance(entrypoints, list) or not all(isinstance(x, str) for x in entrypoints):
        findings.append(
            Finding("error", "config.entrypoints", "entrypoints must be an array of paths", CONFIG_NAME)
        )
        entrypoints = []
    if len(set(entrypoints)) != len(entrypoints):
        findings.append(
            Finding("error", "entrypoint.duplicate", "entrypoints contain duplicates", CONFIG_NAME)
        )

    authorities_raw = config.get("authorities", [])
    if not isinstance(authorities_raw, list):
        findings.append(
            Finding("error", "config.authorities", "authorities must be an array", CONFIG_NAME)
        )
        authorities_raw = []

    authorities: dict[str, dict[str, Any]] = {}
    authority_paths: list[str] = []
    for item in authorities_raw:
        if not isinstance(item, dict):
            findings.append(
                Finding("error", "authority.invalid", "each authority must be an object", CONFIG_NAME)
            )
            continue
        identifier = item.get("id")
        relative = item.get("path")
        if not isinstance(identifier, str) or not identifier:
            findings.append(
                Finding("error", "authority.id", "authority id must be non-empty", CONFIG_NAME)
            )
            continue
        if identifier in authorities:
            findings.append(
                Finding("error", "authority.duplicate", f"duplicate authority id: {identifier}", CONFIG_NAME)
            )
            continue
        if not isinstance(relative, str) or not relative:
            findings.append(
                Finding(
                    "error",
                    "authority.path",
                    f"authority {identifier} has no valid path",
                    CONFIG_NAME,
                )
            )
            continue
        authorities[identifier] = item
        authority_paths.append(relative)

    metrics["authority_count"] = len(authorities)
    checked_docs: list[str] = []
    always_paths: list[str] = []
    for relative in list(entrypoints) + authority_paths:
        if relative in checked_docs:
            continue
        checked_docs.append(relative)
        try:
            path = project_path(root, relative)
        except ValueError as exc:
            findings.append(Finding("error", "path.escapes-root", str(exc), relative))
            continue
        if not path.exists():
            findings.append(
                Finding("error", "document.missing", "configured document does not exist", relative)
            )
            continue
        if not path.is_file():
            findings.append(
                Finding("error", "document.not-file", "configured document is not a file", relative)
            )
            continue
        findings.extend(markdown_link_findings(root, relative))

    for relative in entrypoints:
        path = root / relative
        if not path.is_file():
            continue
        lines = line_count(path)
        metrics["entrypoint_lines"][relative] = lines
        always_paths.append(relative)
        if lines > entrypoint_limit:
            findings.append(
                Finding(
                    "warning",
                    "entrypoint.too-large",
                    f"{lines} lines exceeds configured limit {entrypoint_limit}",
                    relative,
                )
            )

    for authority in authorities.values():
        if authority.get("always") is True:
            always_paths.append(str(authority["path"]))

    always_paths = list(dict.fromkeys(always_paths))
    metrics["always_loaded_chars"] = sum(
        (root / relative).stat().st_size
        for relative in always_paths
        if (root / relative).is_file()
    )
    metrics["always_loaded_documents"] = always_paths
    if metrics["always_loaded_chars"] > context_limit:
        findings.append(
            Finding(
                "warning",
                "context.too-large",
                (
                    f"always-loaded policy is {metrics['always_loaded_chars']} characters; "
                    f"configured limit is {context_limit}"
                ),
                CONFIG_NAME,
            )
        )

    routes = config.get("routes", [])
    if not isinstance(routes, list):
        findings.append(Finding("error", "config.routes", "routes must be an array", CONFIG_NAME))
        routes = []
    route_ids: set[str] = set()
    has_default = False
    for route in routes:
        if not isinstance(route, dict):
            findings.append(Finding("error", "route.invalid", "each route must be an object", CONFIG_NAME))
            continue
        identifier = route.get("id")
        if not isinstance(identifier, str) or not identifier:
            findings.append(Finding("error", "route.id", "route id must be non-empty", CONFIG_NAME))
            continue
        if identifier in route_ids:
            findings.append(
                Finding("error", "route.duplicate", f"duplicate route id: {identifier}", CONFIG_NAME)
            )
        route_ids.add(identifier)
        has_default = has_default or identifier == "default"
        for key in ("terms", "paths", "read", "validation"):
            value = route.get(key, [])
            if not isinstance(value, list) or not all(isinstance(x, str) for x in value):
                findings.append(
                    Finding(
                        "error",
                        f"route.{key}",
                        f"route {identifier} field {key} must be an array of strings",
                        CONFIG_NAME,
                    )
                )
        for authority_id in route.get("read", []):
            if authority_id not in authorities:
                findings.append(
                    Finding(
                        "error",
                        "route.unknown-authority",
                        f"route {identifier} references unknown authority {authority_id}",
                        CONFIG_NAME,
                    )
                )
    metrics["route_count"] = len(route_ids)
    if routes and not has_default:
        findings.append(
            Finding("warning", "route.no-default", "no route named default is configured", CONFIG_NAME)
        )

    capability_findings, capability_ids = validate_capabilities(
        root,
        config,
        capability_owner_limit,
    )
    findings.extend(capability_findings)
    metrics["capability_count"] = len(capability_ids)

    visual_validation = config.get("visual_validation")
    if visual_validation is not None and not isinstance(visual_validation, dict):
        findings.append(
            Finding(
                "error",
                "config.visual-validation",
                "visual_validation must be an object",
                CONFIG_NAME,
            )
        )
        visual_validation = {}
    if isinstance(visual_validation, dict):
        visual_routes = visual_validation.get("routes", [])
        if (
            not isinstance(visual_routes, list)
            or not all(isinstance(route, str) and route for route in visual_routes)
        ):
            findings.append(
                Finding(
                    "error",
                    "visual-validation.routes",
                    "visual_validation.routes must be an array of route ids",
                    CONFIG_NAME,
                )
            )
            visual_routes = []
        for visual_route in visual_routes:
            if visual_route not in route_ids:
                findings.append(
                    Finding(
                        "error",
                        "visual-validation.unknown-route",
                        f"visual validation references unknown route {visual_route}",
                        CONFIG_NAME,
                    )
                )
        configured_positive_int(
            visual_validation.get("artifact_min_count", 1),
            1,
            findings,
            "visual-validation.artifact-count",
            "visual_validation.artifact_min_count must be a positive integer",
        )
        configured_positive_int(
            visual_validation.get("min_review_checks", 1),
            1,
            findings,
            "visual-validation.review-count",
            "visual_validation.min_review_checks must be a positive integer",
        )
        configured_positive_int(
            visual_validation.get("artifact_max_age_seconds", 3600),
            3600,
            findings,
            "visual-validation.artifact-age",
            "visual_validation.artifact_max_age_seconds must be a positive integer",
        )
        require_review = visual_validation.get("require_review", True)
        if visual_routes and require_review is not True:
            findings.append(
                Finding(
                    "error",
                    "visual-validation.review",
                    "configured visual routes must require an explicit review",
                    CONFIG_NAME,
                )
            )
        require_surface = visual_validation.get("require_surface", True)
        if visual_routes and require_surface is not True:
            findings.append(
                Finding(
                    "error",
                    "visual-validation.surface",
                    "configured visual routes must require acceptance-surface metadata",
                    CONFIG_NAME,
                )
            )
        metrics["visual_route_count"] = len(set(visual_routes))

    paragraph_owners: dict[str, list[str]] = {}
    paragraph_samples: dict[str, str] = {}
    for relative in checked_docs:
        path = root / relative
        if not path.is_file() or path.suffix.lower() != ".md":
            continue
        for normalized, sample in normalized_paragraphs(path, duplicate_min).items():
            paragraph_owners.setdefault(normalized, []).append(relative)
            paragraph_samples[normalized] = sample
    for normalized, owners in paragraph_owners.items():
        unique_owners = sorted(set(owners))
        if len(unique_owners) > 1:
            sample = paragraph_samples[normalized][:120]
            findings.append(
                Finding(
                    "warning",
                    "policy.duplicate",
                    f"same long policy paragraph appears in {', '.join(unique_owners)}: {sample!r}",
                )
            )

    tooling = config.get("tooling", {})
    if isinstance(tooling, dict):
        roots = tooling.get("roots", [])
        allowed = tooling.get("allowed", [])
        if isinstance(roots, list) and isinstance(allowed, list):
            for relative_root in roots:
                if not isinstance(relative_root, str):
                    continue
                directory = root / relative_root
                if not directory.exists():
                    continue
                unexpected = [
                    posix(path.relative_to(root))
                    for path in directory.rglob("*")
                    if path.is_file()
                    and not matches_allowed(posix(path.relative_to(root)), allowed)
                ]
                if unexpected:
                    preview = ", ".join(unexpected[:5])
                    suffix = f" (+{len(unexpected) - 5} more)" if len(unexpected) > 5 else ""
                    findings.append(
                        Finding(
                            "warning",
                            "tooling.pollution",
                            f"unexpected runtime/data files in tooling root: {preview}{suffix}",
                            relative_root,
                        )
                    )
        else:
            findings.append(
                Finding(
                    "error",
                    "config.tooling",
                    "tooling.roots and tooling.allowed must be arrays",
                    CONFIG_NAME,
                )
            )

    validation = config.get("validation", {})
    profile_ids: set[str] = set()
    if not isinstance(validation, dict):
        findings.append(
            Finding("error", "config.validation", "validation must be an object", CONFIG_NAME)
        )
        validation = {}
    profiles = validation.get("profiles", {})
    if not isinstance(profiles, dict):
        findings.append(
            Finding("error", "validation.profiles", "validation.profiles must be an object", CONFIG_NAME)
        )
        profiles = {}
    for profile_id, profile in profiles.items():
        profile_ids.add(str(profile_id))
        if not isinstance(profile, dict):
            findings.append(
                Finding(
                    "error",
                    "validation.profile",
                    f"validation profile {profile_id} must be an object",
                    CONFIG_NAME,
                )
            )
            continue
        extends = profile.get("extends", [])
        commands = profile.get("commands", [])
        if not isinstance(extends, list) or not all(isinstance(item, str) for item in extends):
            findings.append(
                Finding(
                    "error",
                    "validation.extends",
                    f"validation profile {profile_id} extends must be an array",
                    CONFIG_NAME,
                )
            )
        if not isinstance(commands, list):
            findings.append(
                Finding(
                    "error",
                    "validation.commands",
                    f"validation profile {profile_id} commands must be an array",
                    CONFIG_NAME,
                )
            )
            continue
        for index, entry in enumerate(commands):
            normalized = normalize_command(entry)
            if normalized is None:
                findings.append(
                    Finding(
                        "error",
                        "validation.command",
                        f"validation profile {profile_id} command {index} is invalid",
                        CONFIG_NAME,
                    )
                )
            elif not normalized[1]:
                findings.append(
                    Finding(
                        "warning",
                        "validation.proof-missing",
                        f"validation profile {profile_id} command {index} does not say what it proves",
                        CONFIG_NAME,
                    )
                )
    for profile_id, profile in profiles.items():
        if not isinstance(profile, dict):
            continue
        for parent in profile.get("extends", []):
            if parent not in profile_ids:
                findings.append(
                    Finding(
                        "error",
                        "validation.unknown-parent",
                        f"validation profile {profile_id} extends unknown profile {parent}",
                        CONFIG_NAME,
                    )
                )
    defaults = validation.get("default_profiles", [])
    if not isinstance(defaults, list) or not all(isinstance(item, str) for item in defaults):
        findings.append(
            Finding(
                "error",
                "validation.defaults",
                "validation.default_profiles must be an array",
                CONFIG_NAME,
            )
        )
        defaults = []
    routed_profile_ids = [
        *defaults,
        *[
            profile
            for route in routes
            if isinstance(route, dict)
            for profile in route.get("validation", [])
        ],
    ]
    for selected in routed_profile_ids:
        if selected not in profile_ids:
            findings.append(
                Finding(
                    "error",
                    "validation.unknown-profile",
                    f"route/default references unknown validation profile {selected}",
                    CONFIG_NAME,
                )
            )
    for selected in profile_ids:
        try:
            expand_validation_profiles(config, [selected])
        except ValueError as exc:
            findings.append(Finding("error", "validation.graph", str(exc), CONFIG_NAME))
    for selected in dict.fromkeys(str(item) for item in routed_profile_ids):
        if selected not in profile_ids:
            continue
        try:
            _, expanded_commands = expand_validation_profiles(config, [selected])
        except ValueError:
            continue
        if not expanded_commands:
            findings.append(
                Finding(
                    "warning",
                    "validation.no-executable-commands",
                    (
                        f"routed validation profile {selected} expands to no commands; "
                        "verification cannot succeed until project-owned checks are configured"
                    ),
                    CONFIG_NAME,
                )
            )

    development_interfaces = config.get("development_interfaces")
    if not isinstance(development_interfaces, list):
        findings.append(
            Finding(
                "error",
                "config.development-interfaces",
                "development_interfaces must be an array",
                CONFIG_NAME,
            )
        )
        development_interfaces = []
    interface_ids: set[str] = set()
    activation_flags: set[str] = set()
    for index, interface in enumerate(development_interfaces):
        if not isinstance(interface, dict):
            findings.append(
                Finding(
                    "error",
                    "development-interface.invalid",
                    f"development interface {index} must be an object",
                    CONFIG_NAME,
                )
            )
            continue
        identifier = interface.get("id")
        if not isinstance(identifier, str) or not identifier.strip():
            findings.append(
                Finding(
                    "error",
                    "development-interface.id",
                    f"development interface {index} needs a non-empty id",
                    CONFIG_NAME,
                )
            )
        elif identifier in interface_ids:
            findings.append(
                Finding(
                    "error",
                    "development-interface.duplicate",
                    f"duplicate development interface id {identifier}",
                    CONFIG_NAME,
                )
            )
        else:
            interface_ids.add(identifier)

        protocol = interface.get("protocol")
        if not isinstance(protocol, str) or not protocol.strip():
            findings.append(
                Finding(
                    "error",
                    "development-interface.protocol",
                    f"development interface {identifier or index} needs a protocol",
                    CONFIG_NAME,
                )
            )

        activation_flag = interface.get("activation_flag")
        if not isinstance(activation_flag, str) or not activation_flag.strip():
            findings.append(
                Finding(
                    "error",
                    "development-interface.activation-flag",
                    (
                        f"development interface {identifier or index} needs exactly one "
                        "non-empty activation_flag"
                    ),
                    CONFIG_NAME,
                )
            )
        elif activation_flag in activation_flags:
            findings.append(
                Finding(
                    "error",
                    "development-interface.duplicate-flag",
                    f"activation flag {activation_flag!r} is used more than once",
                    CONFIG_NAME,
                )
            )
        else:
            activation_flags.add(activation_flag)

        if interface.get("default_enabled") is not False:
            findings.append(
                Finding(
                    "error",
                    "development-interface.default-enabled",
                    (
                        f"development interface {identifier or index} must set "
                        "default_enabled to false"
                    ),
                    CONFIG_NAME,
                )
            )
        production_allowed = interface.get("production_allowed")
        if not isinstance(production_allowed, bool):
            findings.append(
                Finding(
                    "error",
                    "development-interface.production-policy",
                    (
                        f"development interface {identifier or index} must explicitly set "
                        "production_allowed"
                    ),
                    CONFIG_NAME,
                )
            )

        guard_profiles = interface.get("guard_profiles")
        if str(protocol).lower() == "mcp":
            required_guard_kinds = list(MCP_GUARD_KINDS)
            if production_allowed is False:
                required_guard_kinds.append("release")
            if not isinstance(guard_profiles, dict):
                findings.append(
                    Finding(
                        "error",
                        "development-interface.guards",
                        (
                            f"MCP development interface {identifier or index} must map "
                            "each required proof kind to validation profiles"
                        ),
                        CONFIG_NAME,
                    )
                )
                guard_profiles = {}
            unknown_kinds = sorted(
                str(kind)
                for kind in guard_profiles
                if kind not in {*MCP_GUARD_KINDS, "release"}
            )
            if unknown_kinds:
                findings.append(
                    Finding(
                        "error",
                        "development-interface.unknown-proof-kind",
                        (
                            f"MCP development interface {identifier or index} has unknown "
                            f"proof kinds: {', '.join(unknown_kinds)}"
                        ),
                        CONFIG_NAME,
                    )
                )
            for guard_kind in required_guard_kinds:
                selected_profiles = guard_profiles.get(guard_kind)
                if (
                    not isinstance(selected_profiles, list)
                    or not selected_profiles
                    or not all(
                        isinstance(profile, str) and profile
                        for profile in selected_profiles
                    )
                ):
                    findings.append(
                        Finding(
                            "error",
                            "development-interface.missing-proof",
                            (
                                f"MCP development interface {identifier or index} needs "
                                f"non-empty {guard_kind!r} guard profiles"
                            ),
                            CONFIG_NAME,
                        )
                    )
                    continue
                unknown_profiles = [
                    profile
                    for profile in selected_profiles
                    if profile not in profile_ids
                ]
                for guard_profile in unknown_profiles:
                    findings.append(
                        Finding(
                            "error",
                            "development-interface.unknown-profile",
                            (
                                f"development interface {identifier or index} references "
                                f"unknown validation profile {guard_profile}"
                            ),
                            CONFIG_NAME,
                        )
                    )
                if unknown_profiles:
                    continue
                try:
                    _, guard_commands = expand_validation_profiles(
                        config,
                        selected_profiles,
                    )
                except ValueError:
                    continue
                if not guard_commands:
                    findings.append(
                        Finding(
                            "error",
                            "development-interface.empty-proof",
                            (
                                f"MCP development interface {identifier or index} "
                                f"{guard_kind!r} profiles expand to no commands"
                            ),
                            CONFIG_NAME,
                        )
                    )
                elif not any(
                    task_term_matches(proves, guard_kind)
                    for _, proves in guard_commands
                    if proves
                ):
                    findings.append(
                        Finding(
                            "error",
                            "development-interface.unproven-category",
                            (
                                f"MCP development interface {identifier or index} "
                                f"{guard_kind!r} profiles do not explicitly say they "
                                f"prove {guard_kind}"
                            ),
                            CONFIG_NAME,
                        )
                    )
        else:
            if (
                not isinstance(guard_profiles, list)
                or not guard_profiles
                or not all(
                    isinstance(profile, str) and profile
                    for profile in guard_profiles
                )
            ):
                findings.append(
                    Finding(
                        "error",
                        "development-interface.guards",
                        (
                            f"development interface {identifier or index} needs one or "
                            "more guard_profiles"
                        ),
                        CONFIG_NAME,
                    )
                )
            else:
                known_profiles = [
                    profile for profile in guard_profiles if profile in profile_ids
                ]
                for guard_profile in guard_profiles:
                    if guard_profile not in profile_ids:
                        findings.append(
                            Finding(
                                "error",
                                "development-interface.unknown-profile",
                                (
                                    f"development interface {identifier or index} "
                                    f"references unknown validation profile {guard_profile}"
                                ),
                                CONFIG_NAME,
                            )
                        )
                if known_profiles:
                    try:
                        _, guard_commands = expand_validation_profiles(
                            config,
                            known_profiles,
                        )
                    except ValueError:
                        guard_commands = []
                    if not guard_commands:
                        findings.append(
                            Finding(
                                "error",
                                "development-interface.empty-proof",
                                (
                                    f"development interface {identifier or index} guard "
                                    "profiles expand to no commands"
                                ),
                                CONFIG_NAME,
                            )
                        )
    metrics["development_interface_count"] = len(interface_ids)

    adapters = config.get("adapters", {})
    if not isinstance(adapters, dict) or not isinstance(adapters.get("outputs", []), list):
        findings.append(
            Finding("error", "config.adapters", "adapters.outputs must be an array", CONFIG_NAME)
        )
    else:
        output_paths: set[str] = set()
        raw_outputs = adapters.get("outputs", [])
        for index, raw_output in enumerate(raw_outputs):
            if not isinstance(raw_output, dict):
                findings.append(
                    Finding(
                        "error",
                        "adapter.invalid",
                        f"adapter output {index} must be an object",
                        CONFIG_NAME,
                    )
                )
                continue
            kind = raw_output.get("kind")
            path = raw_output.get("path")
            if kind not in {"agents", "copilot"}:
                findings.append(
                    Finding(
                        "error",
                        "adapter.kind",
                        f"adapter output {index} has unknown kind {kind!r}",
                        CONFIG_NAME,
                    )
                )
            if not isinstance(path, str) or not path.strip():
                findings.append(
                    Finding(
                        "error",
                        "adapter.path",
                        f"adapter output {index} needs a non-empty path",
                        CONFIG_NAME,
                    )
                )
        for output in adapter_outputs(config):
            if output["path"] in output_paths:
                findings.append(
                    Finding(
                        "error",
                        "adapter.duplicate",
                        f"duplicate adapter output {output['path']}",
                        CONFIG_NAME,
                    )
                )
            output_paths.add(output["path"])
        findings.extend(generate_adapters(root, config, write=False, force=False))

    findings.extend(route_test_findings(config))
    findings.extend(capability_test_findings(config))

    rules = config.get("rules", [])
    if not isinstance(rules, list):
        findings.append(Finding("error", "config.rules", "rules must be an array", CONFIG_NAME))
        rules = []
    rule_ids: set[str] = set()
    for rule in rules:
        if not isinstance(rule, dict) or not isinstance(rule.get("id"), str):
            findings.append(Finding("error", "rule.invalid", "each rule needs an id", CONFIG_NAME))
            continue
        if rule["id"] in rule_ids:
            findings.append(
                Finding("error", "rule.duplicate", f"duplicate rule id {rule['id']}", CONFIG_NAME)
            )
        rule_ids.add(rule["id"])
        if rule.get("authority") not in authorities:
            findings.append(
                Finding(
                    "error",
                    "rule.authority",
                    f"rule {rule['id']} references unknown authority",
                    CONFIG_NAME,
                )
            )
        source = rule.get("source")
        if not isinstance(source, str) or not source.strip():
            findings.append(
                Finding(
                    "warning",
                    "rule.source",
                    f"rule {rule['id']} has no source citation",
                    CONFIG_NAME,
                )
            )
        else:
            source_path = source.split("#", 1)[0]
            authority = authorities.get(str(rule.get("authority")))
            authority_path = authority.get("path") if isinstance(authority, dict) else None
            if source_path != authority_path:
                findings.append(
                    Finding(
                        "error",
                        "rule.source-authority",
                        (
                            f"rule {rule['id']} source {source_path!r} does not match "
                            f"authority path {authority_path!r}"
                        ),
                        CONFIG_NAME,
                    )
                )
        guard = rule.get("guard")
        if guard and guard not in profile_ids:
            findings.append(
                Finding(
                    "error",
                    "rule.guard",
                    f"rule {rule['id']} references unknown validation profile {guard}",
                    CONFIG_NAME,
                )
            )
        elif guard:
            try:
                _, rule_commands = expand_validation_profiles(config, [str(guard)])
            except ValueError:
                rule_commands = []
            if not rule_commands:
                findings.append(
                    Finding(
                        "error",
                        "rule.empty-guard",
                        (
                            f"rule {rule['id']} guard profile {guard} expands to no "
                            "executable commands"
                        ),
                        CONFIG_NAME,
                    )
                )

    evidence = config.get("evidence", {})
    if (
        not isinstance(evidence, dict)
        or not isinstance(evidence.get("directory"), str)
        or not evidence.get("directory", "").strip()
    ):
        findings.append(
            Finding(
                "error",
                "config.evidence",
                "evidence.directory must be configured as a non-empty relative path",
                CONFIG_NAME,
            )
        )
    else:
        try:
            evidence_directory = project_path(root, evidence["directory"])
        except ValueError as exc:
            findings.append(Finding("error", "evidence.path", str(exc), CONFIG_NAME))
        else:
            git_directory = root / ".git"
            if git_directory.exists():
                normalized_evidence_directory = evidence["directory"].rstrip("/\\")
                probe = (
                    f"{normalized_evidence_directory}/"
                    ".project-agent-toolkit-ignore-probe"
                )
                if not git_ignores_path(root, probe):
                    findings.append(
                        Finding(
                            "error",
                            "evidence.not-ignored",
                            (
                                f"evidence directory {evidence['directory']} is not ignored "
                                "by Git; receipts would mutate the validated working tree"
                            ),
                            ".gitignore",
                        )
                    )

    coverage = coverage_report(config)
    metrics["coverage"] = coverage
    for key in (
        "unrouted_authorities",
        "untested_routes",
        "untested_capabilities",
        "unused_validation_profiles",
        "unguarded_rules",
    ):
        values = coverage[key]
        if values:
            findings.append(
                Finding(
                    "warning",
                    f"coverage.{key.replace('_', '-')}",
                    f"{key.replace('_', ' ')}: {', '.join(values)}",
                    CONFIG_NAME,
                )
            )

    return findings, metrics


def route_details(config: dict[str, Any], task: str, paths: list[str]) -> dict[str, list[str]]:
    authorities = {
        item["id"]: item
        for item in config.get("authorities", [])
        if isinstance(item, dict) and isinstance(item.get("id"), str)
    }
    selected: list[str] = [
        item["id"]
        for item in authorities.values()
        if item.get("always") is True
    ]
    matched_routes: list[str] = []
    validation_profiles: list[str] = []
    task_lower = task.lower()
    non_default_matched = False
    for route in config.get("routes", []):
        if not isinstance(route, dict):
            continue
        identifier = str(route.get("id", ""))
        terms = [str(term).lower() for term in route.get("terms", [])]
        globs = [str(pattern) for pattern in route.get("paths", [])]
        term_match = any(task_term_matches(task_lower, term) for term in terms)
        path_match = any(
            fnmatch.fnmatchcase(posix(path), pattern)
            for path in paths
            for pattern in globs
        )
        matched = term_match or path_match
        if identifier == "default":
            continue
        if matched:
            non_default_matched = True
            matched_routes.append(identifier)
            selected.extend(str(item) for item in route.get("read", []))
            validation_profiles.extend(str(item) for item in route.get("validation", []))
    if not non_default_matched:
        for route in config.get("routes", []):
            if isinstance(route, dict) and route.get("id") == "default":
                matched_routes.append("default")
                selected.extend(str(item) for item in route.get("read", []))
                validation_profiles.extend(str(item) for item in route.get("validation", []))
                break
    documents: list[str] = []
    for identifier in dict.fromkeys(selected):
        authority = authorities.get(identifier)
        if authority and isinstance(authority.get("path"), str):
            documents.append(authority["path"])
    if not validation_profiles:
        validation_profiles.extend(
            str(item)
            for item in config.get("validation", {}).get("default_profiles", [])
        )
    return {
        "routes": list(dict.fromkeys(matched_routes)),
        "documents": documents,
        "validation_profiles": list(dict.fromkeys(validation_profiles)),
    }


def route_documents(root: Path, task: str, paths: list[str]) -> tuple[list[str], list[str]]:
    config, findings = load_config(root)
    if config is None:
        return [], [finding.message for finding in findings]
    details = route_details(config, task, paths)
    return details["documents"], details["routes"]


def validate_capabilities(
    root: Path,
    config: dict[str, Any],
    owner_limit: int,
) -> tuple[list[Finding], set[str]]:
    findings: list[Finding] = []
    raw_capabilities = config.get("capabilities", [])
    if not isinstance(raw_capabilities, list):
        return (
            [
                Finding(
                    "error",
                    "config.capabilities",
                    "capabilities must be an array",
                    CONFIG_NAME,
                )
            ],
            set(),
        )

    capabilities: dict[str, dict[str, Any]] = {}
    for index, capability in enumerate(raw_capabilities):
        if not isinstance(capability, dict):
            findings.append(
                Finding(
                    "error",
                    "capability.invalid",
                    f"capability {index} must be an object",
                    CONFIG_NAME,
                )
            )
            continue
        identifier = capability.get("id")
        if not isinstance(identifier, str) or not identifier.strip():
            findings.append(
                Finding(
                    "error",
                    "capability.id",
                    f"capability {index} needs a non-empty id",
                    CONFIG_NAME,
                )
            )
            continue
        identifier = identifier.strip()
        if identifier in capabilities:
            findings.append(
                Finding(
                    "error",
                    "capability.duplicate",
                    f"duplicate capability id: {identifier}",
                    CONFIG_NAME,
                )
            )
            continue
        capabilities[identifier] = capability

        purpose = capability.get("purpose")
        if not isinstance(purpose, str) or not purpose.strip():
            findings.append(
                Finding(
                    "error",
                    "capability.purpose",
                    f"capability {identifier} needs a concise purpose",
                    CONFIG_NAME,
                )
            )
        for key in ("terms", "paths", "owners", "depends_on"):
            value = capability.get(key, [])
            if (
                not isinstance(value, list)
                or not all(isinstance(item, str) and item.strip() for item in value)
            ):
                findings.append(
                    Finding(
                        "error",
                        f"capability.{key.replace('_', '-')}",
                        (
                            f"capability {identifier} field {key} must be an "
                            "array of non-empty strings"
                        ),
                        CONFIG_NAME,
                    )
                )
        terms = capability.get("terms", [])
        paths = capability.get("paths", [])
        if isinstance(terms, list) and isinstance(paths, list) and not terms and not paths:
            findings.append(
                Finding(
                    "error",
                    "capability.matcher",
                    f"capability {identifier} needs at least one term or path matcher",
                    CONFIG_NAME,
                )
            )
        owners = capability.get("owners", [])
        if isinstance(owners, list):
            if not owners:
                findings.append(
                    Finding(
                        "error",
                        "capability.owners",
                        f"capability {identifier} needs at least one owner path",
                        CONFIG_NAME,
                    )
                )
            if len(owners) > owner_limit:
                findings.append(
                    Finding(
                        "warning",
                        "capability.too-many-owners",
                        (
                            f"capability {identifier} lists {len(owners)} owners; "
                            f"configured limit is {owner_limit}"
                        ),
                        CONFIG_NAME,
                    )
                )
            for owner in owners:
                if not isinstance(owner, str) or not owner.strip():
                    continue
                try:
                    owner_path = project_path(root, owner)
                except ValueError as exc:
                    findings.append(
                        Finding(
                            "error",
                            "capability.owner-path",
                            str(exc),
                            CONFIG_NAME,
                        )
                    )
                    continue
                if not owner_path.exists():
                    findings.append(
                        Finding(
                            "error",
                            "capability.owner-missing",
                            (
                                f"capability {identifier} owner does not exist: "
                                f"{owner}"
                            ),
                            CONFIG_NAME,
                        )
                    )

    for identifier, capability in capabilities.items():
        dependencies = capability.get("depends_on", [])
        if not isinstance(dependencies, list):
            continue
        for dependency in dependencies:
            if dependency == identifier:
                findings.append(
                    Finding(
                        "error",
                        "capability.self-dependency",
                        f"capability {identifier} depends on itself",
                        CONFIG_NAME,
                    )
                )
            elif dependency not in capabilities:
                findings.append(
                    Finding(
                        "error",
                        "capability.unknown-dependency",
                        (
                            f"capability {identifier} references unknown "
                            f"dependency {dependency}"
                        ),
                        CONFIG_NAME,
                    )
                )

    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(identifier: str) -> None:
        if identifier in visited:
            return
        if identifier in visiting:
            findings.append(
                Finding(
                    "error",
                    "capability.dependency-cycle",
                    f"capability dependency cycle includes {identifier}",
                    CONFIG_NAME,
                )
            )
            return
        visiting.add(identifier)
        dependencies = capabilities[identifier].get("depends_on", [])
        if isinstance(dependencies, list):
            for dependency in dependencies:
                if dependency in capabilities:
                    visit(dependency)
        visiting.remove(identifier)
        visited.add(identifier)

    for identifier in capabilities:
        visit(identifier)
    return findings, set(capabilities)


def capability_details(
    config: dict[str, Any],
    task: str,
    paths: list[str],
) -> dict[str, Any]:
    ordered = [
        capability
        for capability in config.get("capabilities", [])
        if isinstance(capability, dict)
        and isinstance(capability.get("id"), str)
    ]
    by_id = {str(capability["id"]): capability for capability in ordered}
    task_lower = task.lower()
    direct = [
        str(capability["id"])
        for capability in ordered
        if (
            any(
                task_term_matches(task_lower, str(term))
                for term in capability.get("terms", [])
            )
            or any(
                fnmatch.fnmatchcase(posix(path), str(pattern))
                for path in paths
                for pattern in capability.get("paths", [])
            )
        )
    ]

    selected: list[str] = []

    def add(identifier: str) -> None:
        if identifier in selected or identifier not in by_id:
            return
        selected.append(identifier)
        for dependency in by_id[identifier].get("depends_on", []):
            add(str(dependency))

    for identifier in direct:
        add(identifier)

    capabilities: list[dict[str, Any]] = []
    owners: list[str] = []
    for identifier in selected:
        capability = by_id[identifier]
        capability_owners = [
            str(owner)
            for owner in capability.get("owners", [])
        ]
        capabilities.append(
            {
                "id": identifier,
                "purpose": str(capability.get("purpose", "")),
                "direct": identifier in direct,
                "owners": capability_owners,
            }
        )
        owners.extend(capability_owners)
    return {
        "capabilities": capabilities,
        "owners": list(dict.fromkeys(owners)),
    }


def context_details(
    config: dict[str, Any],
    task: str,
    paths: list[str],
) -> dict[str, Any]:
    return {
        **route_details(config, task, paths),
        **capability_details(config, task, paths),
    }


def render_adapter(config: dict[str, Any], kind: str) -> str:
    project = config.get("project", {})
    project_name = str(project.get("name", "Project")).strip() or "Project"
    authorities = [
        item
        for item in config.get("authorities", [])
        if isinstance(item, dict)
        and isinstance(item.get("path"), str)
        and isinstance(item.get("id"), str)
    ]
    if kind == "agents":
        return (
            f"{GENERATED_MARKER}\n"
            f"# {project_name} agent instructions\n\n"
            "Read [.github/copilot-instructions.md](.github/copilot-instructions.md).\n"
            f"Use [{CONFIG_NAME}]({CONFIG_NAME}) to load only the authorities routed for\n"
            "the current task and likely changed paths. When a capability map is\n"
            "configured, start code inspection from the owners returned by the toolkit's\n"
            "`context` command. Project-specific policy belongs in routed authorities.\n"
        )
    if kind != "copilot":
        raise ValueError(f"unknown adapter kind: {kind}")

    authority_lines = []
    for index, authority in enumerate(authorities, start=1):
        purpose = str(authority.get("purpose", authority["id"])).strip()
        authority_lines.append(
            f"{index}. [{purpose}](../{posix(authority['path'])})"
        )
    authority_text = "\n".join(authority_lines) or "1. The current user request."
    return (
        f"{GENERATED_MARKER}\n"
        f"# {project_name} agent brief\n\n"
        f"Task routing is defined by [`{CONFIG_NAME}`](../{CONFIG_NAME}). Match the\n"
        "request and likely changed paths, then read every returned authority\n"
        "completely. Do not load unrelated policy just in case.\n\n"
        "## Authority order\n\n"
        f"{authority_text}\n\n"
        "The user's current request controls the task. Lower authorities do not\n"
        "silently override higher ones.\n\n"
        "## Working contract\n\n"
        "- Inspect relevant implementation and version-control state before editing.\n"
        "- Preserve unrelated user changes.\n"
        "- Start from routed capability owners; broaden only when traced dependencies require it.\n"
        "- Decide capability ownership before placing code or policy.\n"
        "- Make the smallest coherent change that achieves the requested outcome.\n"
        "- Validate in proportion to risk and report only current evidence.\n"
        "- Planned, incomplete, stale, or unrun work is not complete.\n"
    )


def adapter_outputs(config: dict[str, Any]) -> list[dict[str, str]]:
    adapters = config.get("adapters", {})
    outputs = adapters.get("outputs", []) if isinstance(adapters, dict) else []
    return [
        {"kind": str(item["kind"]), "path": str(item["path"])}
        for item in outputs
        if isinstance(item, dict) and "kind" in item and "path" in item
    ]


def generate_adapters(root: Path, config: dict[str, Any], write: bool, force: bool) -> list[Finding]:
    findings: list[Finding] = []
    for output in adapter_outputs(config):
        relative = output["path"]
        try:
            target = project_path(root, relative)
            expected = render_adapter(config, output["kind"])
        except ValueError as exc:
            findings.append(Finding("error", "adapter.invalid", str(exc), relative))
            continue
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == expected:
            continue
        if not write:
            findings.append(
                Finding("error", "adapter.stale", "generated adapter is missing or stale", relative)
            )
            continue
        if current is not None and GENERATED_MARKER not in current and not force:
            findings.append(
                Finding(
                    "error",
                    "adapter.unmanaged",
                    "refusing to overwrite an unmanaged adapter without --force",
                    relative,
                )
            )
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        print(f"Generated {relative}")
    return findings


def normalize_command(entry: Any) -> tuple[str, str] | None:
    if isinstance(entry, str) and entry.strip():
        return entry.strip(), ""
    if not isinstance(entry, dict):
        return None
    command = entry.get("run")
    proves = entry.get("proves")
    if not isinstance(command, str) or not command.strip():
        return None
    if not isinstance(proves, str):
        proves = ""
    return command.strip(), proves.strip()


def expand_validation_profiles(config: dict[str, Any], selected: list[str]) -> tuple[list[str], list[tuple[str, str]]]:
    profiles = config.get("validation", {}).get("profiles", {})
    ordered_profiles: list[str] = []
    commands: list[tuple[str, str]] = []
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in ordered_profiles:
            return
        if name in visiting:
            raise ValueError(f"validation profile cycle at {name}")
        profile = profiles.get(name)
        if not isinstance(profile, dict):
            raise ValueError(f"unknown validation profile: {name}")
        visiting.add(name)
        for parent in profile.get("extends", []):
            visit(str(parent))
        visiting.remove(name)
        ordered_profiles.append(name)
        for entry in profile.get("commands", []):
            normalized = normalize_command(entry)
            if normalized and normalized not in commands:
                commands.append(normalized)

    for profile_name in selected:
        visit(profile_name)
    return ordered_profiles, commands


def git_state(root: Path) -> dict[str, Any]:
    def capture(args: list[str]) -> bytes | None:
        result = subprocess.run(
            ["git", *args],
            cwd=root,
            capture_output=True,
            check=False,
        )
        return result.stdout if result.returncode == 0 else None

    revision_bytes = capture(["rev-parse", "HEAD"])
    revision = (
        revision_bytes.decode("utf-8", errors="replace").strip()
        if revision_bytes is not None
        else None
    )
    status = capture(["status", "--porcelain=v1", "-z"])
    if status is None:
        return {
            "revision": None,
            "dirty": None,
            "status_sha256": None,
            "worktree_sha256": None,
        }

    if revision:
        tracked_diff = capture(["diff", "--binary", "--no-ext-diff", "HEAD", "--"])
    else:
        staged = capture(["diff", "--binary", "--no-ext-diff", "--cached", "--"])
        unstaged = capture(["diff", "--binary", "--no-ext-diff", "--"])
        tracked_diff = (staged or b"") + (unstaged or b"")
    untracked_raw = capture(["ls-files", "--others", "--exclude-standard", "-z"]) or b""

    worktree_digest = hashlib.sha256()

    def add_digest_chunk(label: bytes, data: bytes) -> None:
        worktree_digest.update(struct.pack(">I", len(label)))
        worktree_digest.update(label)
        worktree_digest.update(struct.pack(">Q", len(data)))
        worktree_digest.update(data)

    add_digest_chunk(b"status", status)
    add_digest_chunk(b"tracked-diff", tracked_diff or b"")
    for raw_relative in sorted(part for part in untracked_raw.split(b"\0") if part):
        relative = raw_relative.decode("utf-8", errors="surrogateescape")
        try:
            path = project_path(root, relative)
        except ValueError:
            continue
        add_digest_chunk(b"untracked-path", raw_relative)
        if path.is_file():
            add_digest_chunk(
                b"untracked-content",
                bytes.fromhex(file_sha256(path)),
            )
        else:
            add_digest_chunk(b"untracked-content", b"<not-a-file>")

    return {
        "revision": revision,
        "dirty": bool(status),
        "status_sha256": hashlib.sha256(status).hexdigest(),
        "worktree_sha256": worktree_digest.hexdigest(),
    }


def write_receipt(root: Path, config: dict[str, Any], payload: dict[str, Any]) -> Path:
    evidence = config.get("evidence", {})
    relative_dir = (
        str(evidence.get("directory", ".agent-evidence"))
        if isinstance(evidence, dict)
        else ".agent-evidence"
    )
    directory = project_path(root, relative_dir)
    directory.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    revision = payload.get("vcs", {}).get("revision")
    suffix = str(revision)[:8] if revision else "no-vcs"
    target = directory / f"{stamp}-{suffix}.json"
    counter = 1
    while target.exists():
        target = directory / f"{stamp}-{suffix}-{counter}.json"
        counter += 1
    temporary = target.with_suffix(".tmp")
    temporary.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    temporary.replace(target)
    return target


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def inspect_visual_artifact(path: Path) -> dict[str, Any]:
    extension = path.suffix.lower()
    with path.open("rb") as handle:
        header = handle.read(1024 * 1024)
        handle.seek(max(0, path.stat().st_size - 16))
        tail = handle.read(16)

    width: int | None = None
    height: int | None = None
    media_format: str | None = None

    if extension == ".png":
        if len(header) >= 24 and header[:8] == b"\x89PNG\r\n\x1a\n":
            saw_ihdr = False
            saw_idat = False
            saw_iend = False
            with path.open("rb") as handle:
                handle.read(8)
                while True:
                    length_bytes = handle.read(4)
                    if len(length_bytes) != 4:
                        break
                    length = int.from_bytes(length_bytes, "big")
                    chunk_type = handle.read(4)
                    chunk_data = handle.read(length)
                    crc_bytes = handle.read(4)
                    if (
                        len(chunk_type) != 4
                        or len(chunk_data) != length
                        or len(crc_bytes) != 4
                    ):
                        break
                    expected_crc = int.from_bytes(crc_bytes, "big")
                    actual_crc = zlib.crc32(chunk_type)
                    actual_crc = zlib.crc32(chunk_data, actual_crc) & 0xFFFFFFFF
                    if actual_crc != expected_crc:
                        break
                    if chunk_type == b"IHDR" and not saw_ihdr and length == 13:
                        width = int.from_bytes(chunk_data[:4], "big")
                        height = int.from_bytes(chunk_data[4:8], "big")
                        saw_ihdr = True
                    elif chunk_type == b"IDAT":
                        saw_idat = True
                    elif chunk_type == b"IEND" and length == 0:
                        saw_iend = True
                        break
            if saw_ihdr and saw_idat and saw_iend:
                media_format = "png"
    elif extension in {".jpg", ".jpeg"}:
        if header[:2] == b"\xff\xd8":
            cursor = 2
            sof_markers = {
                0xC0,
                0xC1,
                0xC2,
                0xC3,
                0xC5,
                0xC6,
                0xC7,
                0xC9,
                0xCA,
                0xCB,
                0xCD,
                0xCE,
                0xCF,
            }
            while cursor + 4 <= len(header):
                if header[cursor] != 0xFF:
                    cursor += 1
                    continue
                marker = header[cursor + 1]
                cursor += 2
                if marker in {0xD8, 0xD9} or 0xD0 <= marker <= 0xD7:
                    continue
                if cursor + 2 > len(header):
                    break
                segment_length = int.from_bytes(header[cursor : cursor + 2], "big")
                if segment_length < 2 or cursor + segment_length > len(header):
                    break
                if marker in sof_markers and segment_length >= 7:
                    height = int.from_bytes(header[cursor + 3 : cursor + 5], "big")
                    width = int.from_bytes(header[cursor + 5 : cursor + 7], "big")
                    if tail.endswith(b"\xff\xd9"):
                        media_format = "jpeg"
                    break
                cursor += segment_length
    elif extension == ".gif":
        if len(header) >= 10 and header[:6] in {b"GIF87a", b"GIF89a"}:
            width = int.from_bytes(header[6:8], "little")
            height = int.from_bytes(header[8:10], "little")
            if tail.endswith(b";"):
                media_format = "gif"
    elif extension == ".bmp":
        if len(header) >= 26 and header[:2] == b"BM":
            width = abs(int.from_bytes(header[18:22], "little", signed=True))
            height = abs(int.from_bytes(header[22:26], "little", signed=True))
            declared_size = int.from_bytes(header[2:6], "little")
            if declared_size <= path.stat().st_size:
                media_format = "bmp"
    elif extension == ".webp":
        if len(header) >= 30 and header[:4] == b"RIFF" and header[8:12] == b"WEBP":
            chunk = header[12:16]
            if chunk == b"VP8X" and len(header) >= 30:
                width = 1 + int.from_bytes(header[24:27], "little")
                height = 1 + int.from_bytes(header[27:30], "little")
            elif chunk == b"VP8 " and len(header) >= 30 and header[23:26] == b"\x9d\x01\x2a":
                width = int.from_bytes(header[26:28], "little") & 0x3FFF
                height = int.from_bytes(header[28:30], "little") & 0x3FFF
            elif chunk == b"VP8L" and len(header) >= 25 and header[20] == 0x2F:
                bits = int.from_bytes(header[21:25], "little")
                width = (bits & 0x3FFF) + 1
                height = ((bits >> 14) & 0x3FFF) + 1
            declared_size = int.from_bytes(header[4:8], "little") + 8
            if declared_size <= path.stat().st_size:
                media_format = "webp"
    elif extension == ".mp4":
        file_size = path.stat().st_size
        box_types: set[bytes] = set()
        structurally_valid = True
        with path.open("rb") as handle:
            offset = 0
            while offset + 8 <= file_size:
                handle.seek(offset)
                box_header = handle.read(16)
                if len(box_header) < 8:
                    structurally_valid = False
                    break
                box_size = int.from_bytes(box_header[:4], "big")
                box_type = box_header[4:8]
                header_size = 8
                if box_size == 1:
                    if len(box_header) < 16:
                        structurally_valid = False
                        break
                    box_size = int.from_bytes(box_header[8:16], "big")
                    header_size = 16
                elif box_size == 0:
                    box_size = file_size - offset
                if box_size < header_size or offset + box_size > file_size:
                    structurally_valid = False
                    break
                box_types.add(box_type)
                offset += box_size
            if offset != file_size:
                structurally_valid = False
        if (
            structurally_valid
            and {b"ftyp", b"moov", b"mdat"}.issubset(box_types)
        ):
            media_format = "mp4"
    elif extension == ".webm":
        required_elements = (
            b"\x1a\x45\xdf\xa3",  # EBML
            b"\x18\x53\x80\x67",  # Segment
            b"\x16\x54\xae\x6b",  # Tracks
            b"\x1f\x43\xb6\x75",  # Cluster
        )
        if all(element in header for element in required_elements):
            media_format = "webm"

    if media_format is None:
        raise ValueError(
            f"visual artifact is not a valid {extension.lstrip('.')} file: {path.name}"
        )
    if media_format not in {"mp4", "webm"} and (
        not isinstance(width, int)
        or not isinstance(height, int)
        or width < 1
        or height < 1
    ):
        raise ValueError(f"visual artifact has invalid dimensions: {path.name}")
    return {
        "format": media_format,
        "width": width,
        "height": height,
    }


def collect_visual_evidence(
    root: Path,
    config: dict[str, Any],
    routes: list[str],
    changed_paths: list[str],
    artifacts: list[str],
    checks: list[str],
    verdict: str | None,
    surface: str | None,
    references: list[str],
) -> dict[str, Any] | None:
    policy = config.get("visual_validation")
    if not isinstance(policy, dict):
        policy = {}
    configured_routes = [
        str(route)
        for route in policy.get("routes", [])
        if isinstance(route, str)
    ]
    required = bool(set(routes).intersection(configured_routes))
    if (
        not required
        and not artifacts
        and not checks
        and verdict is None
        and not surface
        and not references
    ):
        return None

    minimum = policy.get("artifact_min_count", 1)
    if not isinstance(minimum, int) or isinstance(minimum, bool) or minimum < 1:
        minimum = 1
    if required and len(artifacts) < minimum:
        raise ValueError(
            f"visual verification requires at least {minimum} rendered artifact(s)"
        )

    max_age_seconds = policy.get("artifact_max_age_seconds", 3600)
    if (
        not isinstance(max_age_seconds, int)
        or isinstance(max_age_seconds, bool)
        or max_age_seconds < 1
    ):
        max_age_seconds = 3600
    minimum_checks = policy.get("min_review_checks", 1)
    if (
        not isinstance(minimum_checks, int)
        or isinstance(minimum_checks, bool)
        or minimum_checks < 1
    ):
        minimum_checks = 1
    cleaned_surface = surface.strip() if isinstance(surface, str) else ""
    if required and policy.get("require_surface", True) is True and not cleaned_surface:
        raise ValueError(
            "visual verification requires the real acceptance surface to be named"
        )

    source_mtimes = []
    for relative in changed_paths:
        try:
            source = project_path(root, relative)
        except ValueError:
            continue
        if source.is_file():
            source_mtimes.append(source.stat().st_mtime)
    source_mtime_floor = max(source_mtimes) if source_mtimes else None

    artifact_records: list[dict[str, Any]] = []
    now = time.time()
    for relative in artifacts:
        try:
            path = project_path(root, relative)
        except ValueError as exc:
            raise ValueError(f"invalid visual artifact {relative!r}: {exc}") from exc
        if not path.is_file():
            raise ValueError(f"visual artifact does not exist: {relative}")
        if path.suffix.lower() not in VISUAL_ARTIFACT_EXTENSIONS:
            allowed = ", ".join(sorted(VISUAL_ARTIFACT_EXTENSIONS))
            raise ValueError(
                f"visual artifact must be a rendered image or video ({allowed}): {relative}"
            )
        if path.stat().st_size == 0:
            raise ValueError(f"visual artifact is empty: {relative}")
        artifact_metadata = inspect_visual_artifact(path)
        modified_at = path.stat().st_mtime
        age_seconds = now - modified_at
        if age_seconds > max_age_seconds:
            raise ValueError(
                f"visual artifact is stale ({round(age_seconds, 1)}s old): {relative}"
            )
        if age_seconds < -300:
            raise ValueError(f"visual artifact timestamp is in the future: {relative}")
        if source_mtime_floor is not None and modified_at + 1 < source_mtime_floor:
            raise ValueError(
                f"visual artifact predates a declared changed path: {relative}"
            )
        artifact_records.append(
            {
                "path": normalize_project_relative(relative),
                "size_bytes": path.stat().st_size,
                "sha256": file_sha256(path),
                "modified_at": datetime.fromtimestamp(
                    modified_at,
                    timezone.utc,
                ).isoformat(),
                **artifact_metadata,
            }
        )

    cleaned_checks = [check.strip() for check in checks if check.strip()]
    invalid_checks = [
        check
        for check in cleaned_checks
        if len(check) < 12 or check.lower() in VISUAL_GENERIC_CHECKS
    ]
    if invalid_checks:
        raise ValueError(
            "visual review checks must describe a concrete inspected property"
        )
    require_review = policy.get("require_review", True) is True
    review_supplied = bool(
        required or artifacts or checks or verdict is not None or cleaned_surface
    )
    if review_supplied and require_review:
        if verdict != "pass":
            raise ValueError("visual verification requires an explicit pass verdict")
        if len(cleaned_checks) < minimum_checks:
            raise ValueError(
                f"visual verification requires at least {minimum_checks} concrete review check(s)"
            )
    if verdict == "fail":
        raise ValueError("visual review verdict is fail")

    return {
        "required": required,
        "surface": cleaned_surface or None,
        "references": [item.strip() for item in references if item.strip()],
        "artifacts": artifact_records,
        "checks": cleaned_checks,
        "verdict": verdict,
    }


def verify(
    root: Path,
    config: dict[str, Any],
    task: str,
    paths: list[str],
    claim: str,
    requested_profiles: list[str],
    create_receipt: bool,
    visual_artifacts: list[str] | None = None,
    visual_checks: list[str] | None = None,
    visual_verdict: str | None = None,
    visual_surface: str | None = None,
    visual_references: list[str] | None = None,
) -> tuple[int, dict[str, Any], Path | None]:
    if not claim.strip():
        raise ValueError("verification requires a non-empty claim")
    details = route_details(config, task, paths)
    visual_evidence = collect_visual_evidence(
        root,
        config,
        details["routes"],
        paths,
        visual_artifacts or [],
        visual_checks or [],
        visual_verdict,
        visual_surface,
        visual_references or [],
    )
    selected = requested_profiles or details["validation_profiles"]
    profiles, commands = expand_validation_profiles(config, selected)
    if not commands:
        raise ValueError("selected validation profiles contain no commands")
    config_bytes_before = (root / CONFIG_NAME).read_bytes()
    vcs_before = git_state(root)
    if create_receipt and vcs_before["dirty"] is not None:
        evidence = config.get("evidence", {})
        relative_dir = (
            str(evidence.get("directory", ".agent-evidence"))
            if isinstance(evidence, dict)
            else ".agent-evidence"
        )
        normalized_evidence_dir = relative_dir.rstrip("/\\")
        if not normalized_evidence_dir:
            raise ValueError("evidence.directory must be a non-empty relative path")
        evidence_probe = (
            f"{normalized_evidence_dir}/.project-agent-toolkit-ignore-probe"
        )
        if not git_ignores_path(root, evidence_probe):
            raise ValueError(
                f"evidence directory {relative_dir} must be ignored by Git "
                "before a receipt can be written"
            )
    results: list[dict[str, Any]] = []
    for command, proves in commands:
        print(f"> {command}", flush=True)
        started = time.perf_counter()
        result = subprocess.run(
            command,
            cwd=root,
            shell=True,
            text=True,
            capture_output=True,
            check=False,
        )
        duration_ms = round((time.perf_counter() - started) * 1000, 3)
        if result.stdout:
            print(result.stdout, end="" if result.stdout.endswith("\n") else "\n")
        if result.stderr:
            print(result.stderr, file=sys.stderr, end="" if result.stderr.endswith("\n") else "\n")
        results.append(
            {
                "run": command,
                "proves": proves,
                "exit_code": result.returncode,
                "duration_ms": duration_ms,
                "stdout_sha256": hashlib.sha256(result.stdout.encode("utf-8")).hexdigest(),
                "stderr_sha256": hashlib.sha256(result.stderr.encode("utf-8")).hexdigest(),
            }
        )
    vcs_after = git_state(root)
    config_bytes_after = (root / CONFIG_NAME).read_bytes()
    artifacts_stable = True
    if visual_evidence is not None:
        for artifact in visual_evidence["artifacts"]:
            artifact_path = project_path(root, str(artifact["path"]))
            if (
                not artifact_path.is_file()
                or file_sha256(artifact_path) != artifact["sha256"]
            ):
                artifacts_stable = False
                break
    state_stable = (
        vcs_before == vcs_after
        and config_bytes_before == config_bytes_after
        and artifacts_stable
    )
    commands_passed = all(item["exit_code"] == 0 for item in results)
    payload = {
        "schema": "project-agent-toolkit.evidence.v2",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "project_root": str(root),
        "governance_sha256": hashlib.sha256(config_bytes_before).hexdigest(),
        "vcs": vcs_before,
        "vcs_after": vcs_after,
        "state_stable": state_stable,
        "task": task,
        "paths": paths,
        "claim": claim.strip(),
        "routes": details["routes"],
        "documents": details["documents"],
        "profiles": profiles,
        "results": results,
        "passed": commands_passed and state_stable,
    }
    if visual_evidence is not None:
        payload["visual_evidence"] = visual_evidence
    receipt = write_receipt(root, config, payload) if create_receipt else None
    return (0 if payload["passed"] else 1), payload, receipt


def route_test_findings(config: dict[str, Any]) -> list[Finding]:
    findings: list[Finding] = []
    tests = config.get("route_tests", [])
    if not isinstance(tests, list):
        return [Finding("error", "route-tests.invalid", "route_tests must be an array", CONFIG_NAME)]
    for index, test in enumerate(tests):
        if not isinstance(test, dict):
            findings.append(
                Finding("error", "route-test.invalid", f"route test {index} must be an object", CONFIG_NAME)
            )
            continue
        identifier = str(test.get("id", index))
        task = str(test.get("task", ""))
        paths = test.get("paths", [])
        if not isinstance(paths, list) or not all(isinstance(path, str) for path in paths):
            findings.append(
                Finding("error", "route-test.paths", f"route test {identifier} paths are invalid", CONFIG_NAME)
            )
            continue
        actual = route_details(config, task, paths)
        for field, actual_key in (
            ("expect_routes", "routes"),
            ("expect_documents", "documents"),
            ("expect_validation_profiles", "validation_profiles"),
        ):
            expected = test.get(field)
            if expected is None:
                continue
            if not isinstance(expected, list) or not all(isinstance(item, str) for item in expected):
                findings.append(
                    Finding(
                        "error",
                        "route-test.expectation",
                        f"route test {identifier} field {field} is invalid",
                        CONFIG_NAME,
                    )
                )
                continue
            if actual[actual_key] != expected:
                findings.append(
                    Finding(
                        "error",
                        "route-test.failed",
                        (
                            f"{identifier} expected {actual_key}={expected!r}, "
                            f"got {actual[actual_key]!r}"
                        ),
                        CONFIG_NAME,
                    )
                )
    return findings


