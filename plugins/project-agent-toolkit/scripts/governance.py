def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    root = args.root.expanduser().resolve()
    if args.command == "init":
        return initialize(root, args.profile, args.force)
    if args.command == "route":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        details = route_details(config, args.task, args.path)
        if args.json:
            print(json.dumps(details, indent=2))
        else:
            print(
                f"Matched routes: "
                f"{', '.join(details['routes']) if details['routes'] else 'none'}"
            )
            for document in details["documents"]:
                print(document)
            if details["validation_profiles"]:
                print(f"Validation: {', '.join(details['validation_profiles'])}")
        return 0 if details["documents"] else 1
    if args.command == "context":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        details = context_details(config, args.task, args.path)
        if args.json:
            print(json.dumps(details, indent=2))
        else:
            print(
                f"Matched routes: "
                f"{', '.join(details['routes']) if details['routes'] else 'none'}"
            )
            for document in details["documents"]:
                print(document)
            if details["capabilities"]:
                print("Capability owners:")
                for capability in details["capabilities"]:
                    dependency = "" if capability["direct"] else " (dependency)"
                    print(
                        f"  {capability['id']}{dependency}: "
                        f"{capability['purpose']}"
                    )
                    for owner in capability["owners"]:
                        print(f"    {owner}")
            if details["validation_profiles"]:
                print(f"Validation: {', '.join(details['validation_profiles'])}")
        return 0 if details["documents"] else 1
    if args.command == "route-test":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        findings = [
            *route_test_findings(config),
            *capability_test_findings(config),
        ]
        if args.json:
            print(json.dumps([asdict(finding) for finding in findings], indent=2))
        elif findings:
            for finding in findings:
                print(f"{finding.severity.upper()} {finding.code}: {finding.message}")
        else:
            contract_count = len(config.get("route_tests", [])) + len(
                config.get("capability_tests", [])
            )
            print(f"route-test: OK ({contract_count} contract(s))")
        return 1 if any(finding.severity == "error" for finding in findings) else 0
    if args.command == "generate":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        findings = generate_adapters(root, config, args.write, args.force)
        for finding in findings:
            print(
                f"{finding.severity.upper()} {finding.code}: {finding.message}",
                file=sys.stderr,
            )
        if not findings:
            print("generate: OK")
        return 1 if findings else 0
    if args.command == "verify":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        try:
            status, payload, receipt = verify(
                root,
                config,
                args.task,
                args.path,
                args.claim,
                args.profile,
                not args.no_receipt,
                args.visual_artifact,
                args.visual_check,
                args.visual_verdict,
                args.visual_surface,
                args.visual_reference,
            )
        except ValueError as exc:
            print(f"verify: {exc}", file=sys.stderr)
            return 1
        if args.json:
            print(json.dumps({"receipt": str(receipt) if receipt else None, **payload}, indent=2))
        elif receipt:
            print(f"Evidence receipt: {receipt}")
        return status
    if args.command == "coverage":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        report = coverage_report(config)
        if args.json:
            print(json.dumps(report, indent=2))
        else:
            print(f"Governance coverage: {'complete' if report['complete'] else 'gaps found'}")
            for key, value in report.items():
                if key != "complete" and value:
                    print(f"  {key}: {value}")
        return 1 if args.strict and not report["complete"] else 0
    if args.command == "upgrade":
        config, config_findings = load_config(root)
        if config is None:
            for finding in config_findings:
                print(f"ERROR {finding.message}", file=sys.stderr)
            return 1
        try:
            migrated = migrate_config(config)
        except ValueError as exc:
            print(f"upgrade: {exc}", file=sys.stderr)
            return 1
        changed = migrated != config
        if args.json or not args.write:
            print(json.dumps(migrated, indent=2))
        if args.write and changed:
            target = root / CONFIG_NAME
            temporary = target.with_suffix(".tmp")
            temporary.write_text(json.dumps(migrated, indent=2) + "\n", encoding="utf-8")
            temporary.replace(target)
            print(f"Upgraded {CONFIG_NAME} to version {CURRENT_VERSION}")
            if ensure_evidence_ignore(root):
                print("Updated .gitignore additively for transient evidence")
        elif not changed:
            print(f"upgrade: already at version {CURRENT_VERSION}")
        return 0

    findings, metrics = audit(root)
    print_audit(findings, metrics, args.json)
    has_errors = any(finding.severity == "error" for finding in findings)
    has_warnings = any(finding.severity == "warning" for finding in findings)
    if args.command == "check":
        return 1 if has_errors or has_warnings else 0
    return 1 if has_errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
